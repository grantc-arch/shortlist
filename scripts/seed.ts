/** A minimal one-page PDF so demo CVs open in the browser. */
function demoCv(name: string, lines: string[]): Buffer {
  const esc = (s: string) => s.replace(/[\\()]/g, (c) => `\\${c}`);
  const text = [
    "BT /F1 20 Tf 60 770 Td",
    `(${esc(name)}) Tj`,
    "/F1 11 Tf 0 -22 Td",
    "(Curriculum vitae - demo document generated by Shortlist) Tj",
    ...lines.flatMap((l) => ["0 -18 Td", `(${esc(l)}) Tj`]),
    "ET",
  ].join("\n");
  const objects = [
    "<< /Type /Catalog /Pages 2 0 R >>",
    "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
    "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>",
    `<< /Length ${Buffer.byteLength(text)} >>\nstream\n${text}\nendstream`,
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
  ];
  let pdf = "%PDF-1.4\n";
  const offsets: number[] = [];
  objects.forEach((o, i) => {
    offsets.push(Buffer.byteLength(pdf));
    pdf += `${i + 1} 0 obj\n${o}\nendobj\n`;
  });
  const xref = Buffer.byteLength(pdf);
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  pdf += offsets.map((o) => `${String(o).padStart(10, "0")} 00000 n \n`).join("");
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`;
  return Buffer.from(pdf);
}

async function createEmployer(email: string, companyName: string, city: string, about: string, website?: string) {
  const [u] = await db
    .insert(schema.users)
    .values({ email, passwordHash: await bcrypt.hash(PASSWORD, 10), role: "employer", createdAt: daysAgo(30) })
    .returning();
  // isDemo keeps these fictional companies' jobs labelled on the site and off Google.
  await db.insert(schema.employers).values({ userId: u.id, companyName, city, about, website, isDemo: true });
  return u.id;
}

type CandidateSeed = Omit<typeof schema.candidates.$inferInsert, "userId" | "cvData" | "cvFileName" | "popiaConsentAt"> & {
  email: string;
  cvLines: string[];
};

async function createCandidate(c: CandidateSeed) {
  const { email, cvLines, ...profile } = c;
  const [u] = await db
    .insert(schema.users)
    .values({ email, passwordHash: await bcrypt.hash(PASSWORD, 10), role: "candidate", createdAt: daysAgo(20) })
    .returning();
  await db.insert(schema.candidates).values({
    ...profile,
    skills: normaliseSkills(profile.skills ?? []),
    userId: u.id,
    cvFileName: `${profile.fullName.replace(/\s+/g, "_")}_CV.pdf`,
    cvData: demoCv(profile.fullName, cvLines),
    popiaConsentAt: daysAgo(20),
  });
  return u.id;
}

